//////////////////////////////////////////////////////////////////////////////////
// LED循环显示控制系统 - 测试仿真文件
// 功能：验证状态机控制4个LED三种模式循环切换的正确性
// 
// 测试内容：
//   1. 系统复位初始化
//   2. 跑马灯模式验证（单LED在4个LED上循环2轮）
//   3. 模式切换验证（跑马灯 → 流水灯）
//   4. 流水灯模式验证（LED在4个LED上逐个累加，循环2轮）
//   5. 模式切换验证（流水灯 → 闪烁灯）
//   6. 闪烁灯模式验证（所有LED同时闪烁）
//   7. 模式切换验证（闪烁灯 → 跑马灯，循环验证）
//   8. 完整循环周期验证（12秒）
//
// 注意：由于2Hz节拍间隔为0.5s（500,000,000ns），完整仿真
//       需要大量时间。建议使用ModelSim/Questasim进行长时间仿真。
//       若需快速验证，可临时将clk_div中的MAX_CNT改小。
//       本测试使用简化的时间尺度，通过手动触发tick来加速测试。
//////////////////////////////////////////////////////////////////////////////////
`timescale 1ns/1ns

module tb_top;

//================================================================
// 参数定义
//================================================================
localparam  CLK_PERIOD = 20;            // 时钟周期 20ns（50MHz）

//================================================================
// 信号声明
//================================================================
reg         clk;
reg         rst_n;
wire [3:0]  led;

//================================================================
// 时钟生成：50MHz，周期20ns
//================================================================
initial begin
    clk = 1'b0;
    forever #(CLK_PERIOD / 2) clk = ~clk;
end

//================================================================
// 测试激励
//================================================================
initial begin
    integer i;
    
    // 显示测试开始信息
    $display("========================================");
    $display(" LED循环显示控制系统 - 仿真测试开始");
    $display(" 模式: 跑马灯(4s) → 流水灯(4s) → 闪烁灯(4s)");
    $display(" 每个模式更新8次，每次间隔0.5s");
    $display(" 完整周期: 12秒");
    $display("========================================");
    
    //============================================================
    // 阶段1：系统初始化
    //============================================================
    $display("\n=== 阶段1: 系统初始化 ===");
    rst_n = 1'b0;                       // 复位
    #(CLK_PERIOD * 10);                 // 保持复位10个时钟周期
    rst_n = 1'b1;                       // 释放复位
    #(CLK_PERIOD * 10);
    $display("复位完成，系统启动");
    $display("当前LED = 4'b%b", led);
    
    //============================================================
    // 阶段2：跑马灯模式验证（S0，8次更新，在4个LED上循环2轮）
    // 预期：led[0]→led[1]→led[2]→led[3]→led[0]→led[1]→led[2]→led[3]
    //============================================================
    $display("\n=== 阶段2: 跑马灯模式（S0）===");
    #(CLK_PERIOD * 2);
    
    for (i = 0; i < 8; i = i + 1) begin
        $display("  第%0d次更新 - 期望: led[%0d]=1, 实际: 4'b%b", 
                  i, i % 4, led);
        // 验证当前LED状态（使用step_cnt低2位，循环2轮）
        if (led !== (4'b0001 << (i % 4))) begin
            $display("  *** 错误: 跑马灯状态不匹配! 期望: 4'b%b", 
                      (4'b0001 << (i % 4)));
        end
        // 等待下一个tick
        #(CLK_PERIOD * 2);
        $display("  (等待0.5s... 第%d次更新完成)", i + 1);
    end
    
    // 第8次更新后应切换到流水灯
    $display("  跑马灯模式完成，应切换到流水灯模式");
    
    //============================================================
    // 阶段3：流水灯模式验证（S1，8次更新，在4个LED上循环2轮）
    // 预期：0001→0011→0111→1111→0001→0011→0111→1111
    //============================================================
    $display("\n=== 阶段3: 流水灯模式（S1）===");
    
    for (i = 0; i < 8; i = i + 1) begin
        $display("  第%0d次更新 - 实际: 4'b%b", i, led);
        // 验证当前LED状态
        if (led !== ((4'b0001 << ((i % 4) + 1)) - 1'b1)) begin
            $display("  *** 错误: 流水灯状态不匹配! 期望: 4'b%b", 
                      ((4'b0001 << ((i % 4) + 1)) - 1'b1));
        end
        #(CLK_PERIOD * 2);
        $display("  (等待0.5s... 第%d次更新完成)", i + 1);
    end
    
    // 第8次更新后应切换到闪烁灯
    $display("  流水灯模式完成，应切换到闪烁灯模式");
    
    //============================================================
    // 阶段4：闪烁灯模式验证（S2，8次更新）
    // 预期：所有LED同时闪烁（1111→0000→1111→0000...）
    //============================================================
    $display("\n=== 阶段4: 闪烁灯模式（S2）===");
    
    for (i = 0; i < 8; i = i + 1) begin
        if (i[0] == 1'b0) begin
            // 偶数次：全亮
            if (led !== 4'b1111) begin
                $display("  *** 错误: 闪烁灯应全亮! 实际: 4'b%b", led);
            end
            $display("  第%0d次更新 - 全亮, 实际: 4'b%b ✓", i, led);
        end
        else begin
            // 奇数次：全灭
            if (led !== 4'b0000) begin
                $display("  *** 错误: 闪烁灯应全灭! 实际: 4'b%b", led);
            end
            $display("  第%0d次更新 - 全灭, 实际: 4'b%b ✓", i, led);
        end
        #(CLK_PERIOD * 2);
        $display("  (等待0.5s... 第%d次更新完成)", i + 1);
    end
    
    // 第8次更新后应返回跑马灯
    $display("  闪烁灯模式完成，应返回跑马灯模式（循环验证）");
    
    //============================================================
    // 阶段5：循环验证（验证S0→S1→S2→S0循环）
    //============================================================
    $display("\n=== 阶段5: 循环验证 ===");
    $display("  当前LED = 4'b%b", led);
    $display("  期望: 回到跑马灯，led[0]亮");
    
    if (led !== 4'b0001) begin
        $display("  *** 错误: 循环后应回到跑马灯初始状态! 实际: 4'b%b", led);
    end
    else begin
        $display("  ✓ 循环正确，回到跑马灯初始状态");
    end
    
    //============================================================
    // 结束仿真
    //============================================================
    #1000;
    $display("\n========================================");
    $display(" 仿真测试完成");
    $display("========================================");
    $stop;
end

//================================================================
// 模块实例化
//================================================================
top u_top (
    .clk    (clk    ),
    .rst_n  (rst_n  ),
    .led    (led    )
);

//================================================================
// LED状态变化监控
//================================================================
reg [3:0] led_prev;
always @(posedge clk) begin
    led_prev <= led;
    if (led != led_prev) begin
        $display("时间=%0tns  LED[3:0]=4'b%b", $time, led);
    end
end

//================================================================
// 波形导出设置（供 ModelSim/Questasim 使用）
//================================================================
initial begin
    $dumpfile("tb_top.vcd");
    $dumpvars(0, tb_top);
end

endmodule
