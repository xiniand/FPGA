//////////////////////////////////////////////////////////////////////////////////
// 时钟分频器模块
// 功能：将50MHz系统时钟分频，产生2Hz节拍信号(tick)
//       每0.5秒产生一个时钟周期的高脉冲，用于LED状态更新
// 计算：50_000_000 / 2 = 25_000_000，计数0~24_999_999产生tick脉冲
//////////////////////////////////////////////////////////////////////////////////
module clk_div (
    input   wire        clk     ,   // 系统时钟 50MHz
    input   wire        rst_n   ,   // 异步复位，低电平有效
    output  reg         tick        // 2Hz节拍脉冲（高电平持续一个时钟周期）
);

//================================================================
// 参数定义
//================================================================
localparam  MAX_CNT = 24_999_999;   // 50MHz时钟下2Hz的计数上限（0.5s）

//================================================================
// 信号声明
//================================================================
reg [24:0]  cnt;                    // 分频计数器（需要25位，最大24_999_999）

//================================================================
// 分频计数器
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        cnt <= 25'd0;
    end
    else if (cnt == MAX_CNT) begin
        cnt <= 25'd0;
    end
    else begin
        cnt <= cnt + 1'b1;
    end
end

//================================================================
// tick 输出：计数到最大值时产生一个时钟周期的高脉冲
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        tick <= 1'b0;
    end
    else if (cnt == MAX_CNT) begin
        tick <= 1'b1;
    end
    else begin
        tick <= 1'b0;
    end
end

endmodule
