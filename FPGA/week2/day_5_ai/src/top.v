//////////////////////////////////////////////////////////////////////////////////
// LED循环显示控制系统 - 顶层模块
// 功能：实例化时钟分频器和LED控制器，完成信号连接
// 
// 系统概述：
//   - 使用状态机控制4个LED灯（硬件平台 AWC C4 DVK）
//   - 三种模式循环切换：跑马灯 → 流水灯 → 闪烁灯
//   - 每个模式持续4秒，每0.5秒更新一次显示状态
//   - 完整循环周期：12秒
//   - 无限循环
//
// 硬件平台：Cyclone IV E (EP4CE6F17C8N)
// 系统时钟：50MHz
// LED引脚分配：led[3]=PIN_D16, led[2]=PIN_F15,
//              led[1]=PIN_F16, led[0]=PIN_G15
//////////////////////////////////////////////////////////////////////////////////
module top (
    input   wire        clk     ,   // 系统时钟 50MHz
    input   wire        rst_n   ,   // 复位按键，低电平有效
    output  wire [3:0]  led         // 4位LED输出
);

//================================================================
// 信号声明
//================================================================
wire        tick;                   // 2Hz节拍信号（每0.5秒一个脉冲）

//================================================================
// 模块实例化
//================================================================

// 时钟分频器：产生2Hz节拍（0.5s）
clk_div u_clk_div (
    .clk    (clk        ),
    .rst_n  (rst_n      ),
    .tick   (tick       )
);

// LED循环显示控制器（状态机版）
led_ctrl u_led_ctrl (
    .clk    (clk        ),
    .rst_n  (rst_n      ),
    .tick   (tick       ),
    .led    (led        )
);

endmodule
