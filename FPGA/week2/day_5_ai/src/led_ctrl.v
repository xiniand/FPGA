//////////////////////////////////////////////////////////////////////////////////
// LED循环显示控制器（状态机版）
// 功能：使用状态机控制4个LED灯，实现三种显示模式循环切换
// 
// 三种显示模式：
//   跑马灯（S0）- 单LED从左向右逐位移位（循环2轮），持续4秒
//   流水灯（S1）- LED从第一个开始逐个累加点亮（循环2轮），持续4秒
//   闪烁灯（S2）- 所有LED同时闪烁（亮0.5s/灭0.5s），持续4秒
//
// 核心参数：
//   LED数量：4个（硬件平台 AWC C4 DVK）
//   每个状态持续时间：4秒
//   更新间隔：0.5秒
//   每个状态更新次数：4秒 ÷ 0.5秒 = 8次
//
// 状态转移：S0 → S1 → S2 → S0（循环往复）
// 完整循环周期：12秒
//
// LED排列：led[3] led[2] led[1] led[0]（从左到右）
//
// 时序说明（4个LED）：
//   第0~4秒：跑马灯（S0）— 循环2轮
//     第0.0s进入状态 → led[0]亮
//     第0.5s → led[1]亮，led[0]灭
//     第1.0s → led[2]亮，led[1]灭
//     第1.5s → led[3]亮，led[2]灭
//     第2.0s → led[0]亮（第2轮）
//     第2.5s → led[1]亮
//     第3.0s → led[2]亮
//     第3.5s → led[3]亮
//     第4.0s → 达到8次更新，切换到流水灯
//
//   第4~8秒：流水灯（S1）— 循环2轮
//     第4.0s进入状态 → led[0]亮
//     第4.5s → led[0:1]亮
//     第5.0s → led[0:2]亮
//     第5.5s → led[0:3]全亮
//     第6.0s → led[0]亮（第2轮）
//     第6.5s → led[0:1]亮
//     第7.0s → led[0:2]亮
//     第7.5s → led[0:3]全亮
//     第8.0s → 达到8次更新，切换到闪烁灯
//
//   第8~12秒：闪烁灯（S2）
//     第8.0s进入状态 → 全亮
//     第8.5s → 全灭
//     ...交替（4次亮灭）...
//     第11.5s → 全灭
//     第12.0s → 达到8次更新，返回跑马灯
//////////////////////////////////////////////////////////////////////////////////
module led_ctrl (
    input   wire        clk     ,   // 系统时钟 50MHz
    input   wire        rst_n   ,   // 异步复位，低电平有效
    input   wire        tick    ,   // 2Hz节拍脉冲（每0.5秒一个脉冲）
    output  reg [3:0]   led         // 4位LED输出（硬件只有4个LED）
);

//================================================================
// 参数定义
//================================================================
localparam  S0 = 2'b00;    // 跑马灯状态（Running Horse）
localparam  S1 = 2'b01;    // 流水灯状态（Water Flow）
localparam  S2 = 2'b10;    // 闪烁灯状态（Blinking）

//================================================================
// 信号声明
//================================================================
reg [1:0]   state;          // 当前状态寄存器
reg [1:0]   next_state;     // 下一状态（组合逻辑）
reg [3:0]   step_cnt;       // 步进计数器（0~8，每个状态更新8次）
reg [3:0]   led_next;       // LED下一周期值（组合逻辑）

//================================================================
// 状态寄存器
// 在tick到达且step_cnt=8时切换到下一状态
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        state <= S0;
    end
    else if (tick && (step_cnt == 4'd8)) begin
        state <= next_state;
    end
    else begin
        state <= state;
    end
end

//================================================================
// 次态逻辑（组合逻辑）
// S0 → S1 → S2 → S0（循环）
//================================================================
always @(*) begin
    case (state)
        S0 : next_state = S1;
        S1 : next_state = S2;
        S2 : next_state = S0;
        default : next_state = S0;
    endcase
end

//================================================================
// 步进计数器
// 每个tick递增一次，0→1→2→...→7→8
// 当step_cnt=8时状态切换，计数器重置为0
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        step_cnt <= 4'd0;
    end
    else if (tick) begin
        if (step_cnt == 4'd8) begin
            step_cnt <= 4'd0;       // 状态切换，重置计数器
        end
        else begin
            step_cnt <= step_cnt + 1'b1;    // 正常递增
        end
    end
    else begin
        step_cnt <= step_cnt;
    end
end

//================================================================
// LED输出寄存器
// 每个tick更新一次LED状态
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        led <= 4'b0000;
    end
    else if (tick) begin
        led <= led_next;
    end
    else begin
        led <= led;
    end
end

//================================================================
// LED次态组合逻辑
// 根据当前状态和步进计数器计算LED下一值
//
// 因硬件只有4个LED（AWC C4 DVK），step_cnt[1:0]取低2位
// 使4个LED在8次更新中循环2轮
//
// 跑马灯（S0）：单LED从左向右移动
//   led_next = 4'b0001 << step_cnt[1:0]
//   例：step_cnt=0 → 4'b0001（led[0]亮）
//       step_cnt=3 → 4'b1000（led[3]亮）
//       step_cnt=4 → 4'b0001（第2轮，led[0]亮）
//       step_cnt=7 → 4'b1000（第2轮，led[3]亮）
//
// 流水灯（S1）：LED从第一个开始逐个累加点亮
//   led_next = (4'b0001 << (step_cnt[1:0] + 1)) - 1'b1
//   例：step_cnt=0 → (1<<1)-1 = 1 → 0001（led[0]亮）
//       step_cnt=3 → (1<<4)-1 = 15 → 1111（全亮）
//       step_cnt=4 → (1<<1)-1 = 1 → 0001（第2轮）
//
// 闪烁灯（S2）：所有LED同时闪烁
//   step_cnt为偶数 → 全亮
//   step_cnt为奇数 → 全灭
//================================================================
always @(*) begin
    case (state)
        //========================================================
        // S0：跑马灯（使用step_cnt低2位，在4个LED上循环2轮）
        //========================================================
        S0 : begin
            led_next = 4'b0001 << step_cnt[1:0];
        end
        
        //========================================================
        // S1：流水灯（使用step_cnt低2位，在4个LED上循环2轮）
        //========================================================
        S1 : begin
            led_next = (4'b0001 << (step_cnt[1:0] + 1)) - 1'b1;
        end
        
        //========================================================
        // S2：闪烁灯
        //========================================================
        S2 : begin
            // step_cnt[0]为1表示奇数步
            if (step_cnt[0]) begin
                led_next = 4'b0000;    // 奇数步：全灭
            end
            else begin
                led_next = 4'b1111;    // 偶数步：全亮
            end
        end
        
        default : begin
            led_next = 4'b0000;
        end
    endcase
end

endmodule
