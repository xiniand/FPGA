//////////////////////////////////////////////////////////////////////////////////
// 按键消抖模块
// 功能：滤除机械按键的抖动，输出稳定的按键电平
// 方法：
//   1. 两级同步寄存器防止亚稳态
//   2. 计数器延时采样（20ms），等待按键信号稳定
//   3. 输出消抖后的按键电平
// 参数：
//   - 系统时钟 50MHz
//   - 消抖时间 20ms（计数 1_000_000 个时钟周期）
//////////////////////////////////////////////////////////////////////////////////
module key_debounce (
    input   wire        clk     ,   // 系统时钟 50MHz
    input   wire        rst_n   ,   // 异步复位，低电平有效
    input   wire        key_in  ,   // 按键输入（未经消抖）
    output  reg         key_out     // 消抖后输出
);

//================================================================
// 参数定义
//================================================================
localparam  MAX_CNT = 1_000_000 - 1;    // 20ms消抖时间（50MHz时钟）
                                        // 50_000_000 × 0.02 = 1_000_000

//================================================================
// 信号声明
//================================================================
reg [19:0]  cnt;                    // 消抖计数器
reg         sync_1;                 // 第一级同步寄存器
reg         sync_2;                 // 第二级同步寄存器
reg         key_stable;             // 稳定后的按键电平

//================================================================
// 两级同步寄存器：消除亚稳态
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        sync_1 <= 1'b0;
        sync_2 <= 1'b0;
    end
    else begin
        sync_1 <= key_in;
        sync_2 <= sync_1;
    end
end

//================================================================
// 消抖计数器：当同步后的电平稳定时开始计数
// 计数到 MAX_CNT 则认为按键信号已稳定，更新输出
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        cnt         <= 20'd0;
        key_stable  <= 1'b0;
        key_out     <= 1'b0;
    end
    else begin
        // 如果同步后的值与当前稳定值不同，说明按键正在变化
        if (sync_2 != key_stable) begin
            cnt <= cnt + 1'b1;              // 开始计数
            // 计数达到消抖时间，认为信号已稳定
            if (cnt == MAX_CNT) begin
                cnt         <= 20'd0;
                key_stable  <= sync_2;      // 更新稳定值
                key_out     <= sync_2;      // 输出稳定后的电平
            end
        end
        else begin
            cnt <= 20'd0;                    // 信号相同，计数器清零
        end
    end
end

endmodule
