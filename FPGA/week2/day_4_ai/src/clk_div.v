//////////////////////////////////////////////////////////////////////////////////
// 时钟分频器模块
// 功能：将50MHz系统时钟分频，产生4Hz节拍信号(tick)
//       用于转向灯2Hz闪烁控制（每0.25s翻转一次LED状态）
// 计算：50_000_000 / 4 = 12_500_000，计数0~12_499_999产生tick脉冲
//////////////////////////////////////////////////////////////////////////////////
module clk_div (
    input   wire        clk     ,   // 系统时钟 50MHz
    input   wire        rst_n   ,   // 异步复位，低电平有效
    output  reg         tick        // 4Hz节拍脉冲（高电平持续一个时钟周期）
);

//================================================================
// 参数定义
//================================================================
localparam  MAX_CNT = 12_499_999;   // 50MHz时钟下4Hz的计数上限

//================================================================
// 信号声明
//================================================================
reg [23:0]  cnt;                    // 分频计数器

//================================================================
// 分频计数器
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        cnt <= 24'd0;
    end
    else if (cnt == MAX_CNT) begin
        cnt <= 24'd0;
    end
    else begin
        cnt <= cnt + 1'b1;
    end
end

//================================================================
// tick 输出：计数到最大值时产生一个时钟周期的高脉冲
//================================================================
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        tick <= 1'b0;
    end
    else if (cnt == MAX_CNT) begin
        tick <= 1'b1;
    end
    else begin
        tick <= 1'b0;
    end
end

endmodule
