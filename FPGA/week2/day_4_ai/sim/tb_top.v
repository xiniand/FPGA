//////////////////////////////////////////////////////////////////////////////////
// 转向灯控制系统 - 测试仿真文件
// 功能：验证各模块功能正确性
// 
// 测试用例：
//   1. 左转按键 → LED从右往左流水（led[0]→led[1]→led[2]→led[3]）
//   2. 右转按键 → LED从左往右流水（led[3]→led[2]→led[1]→led[0]）
//   3. 双闪按键 → 所有LED同时闪烁
//   4. 同时按下左+右 → 进入双闪模式
//   5. 按键消抖功能验证
//   6. 模式切换功能验证
//
// 注意：由于4Hz流水的步进周期为250ms（250,000,000ns），
//       完整仿真需要大量时间。建议使用ModelSim/Questasim
//       进行长时间仿真，或观察LED监控打印输出。
//       若需快速验证，可临时将clk_div中的MAX_CNT改小。
//////////////////////////////////////////////////////////////////////////////////
`timescale 1ns/1ns

module tb_top;

//================================================================
// 信号声明
//================================================================
reg         clk;
reg         rst_n;
reg         key_left;
reg         key_right;
reg         key_haz;
wire [3:0]  led;

//================================================================
// 时钟生成：50MHz，周期20ns
//================================================================
initial begin
    clk = 1'b0;
    forever #10 clk = ~clk;
end

//================================================================
// 测试激励
//================================================================
initial begin
    // 初始化
    rst_n       = 1'b0;
    key_left    = 1'b1;     // 高电平=未按下（外部低电平有效）
    key_right   = 1'b1;
    key_haz     = 1'b1;
    
    // 复位
    #100;
    rst_n = 1'b1;
    #100;
    
    //============================================================
    // 测试用例1：左转功能
    // 模拟按键按下（低电平），带抖动
    //============================================================
    $display("=== 测试1: 左转功能 ===");
    // 模拟按键抖动（约5ms）
    key_left = 1'b0;    #1000;
    key_left = 1'b1;    #500;
    key_left = 1'b0;    #800;
    key_left = 1'b1;    #300;
    key_left = 1'b0;    #2000;
    // 稳定按下（超过20ms消抖时间）
    #25_000_000;        // 等待约25ms，让消抖完成并观察LED闪烁
    
    // 释放按键（也带抖动）
    key_left = 1'b1;    #1000;
    key_left = 1'b0;    #500;
    key_left = 1'b1;    #300;
    key_left = 1'b0;    #800;
    key_left = 1'b1;
    
    // 等待观察模式是否退出
    #30_000_000;        // 等待约30ms
    
    //============================================================
    // 测试用例2：右转功能
    //============================================================
    $display("=== 测试2: 右转功能 ===");
    key_right = 1'b0;   #1000;
    key_right = 1'b1;   #500;
    key_right = 1'b0;   #800;
    key_right = 1'b1;   #300;
    key_right = 1'b0;
    
    #30_000_000;        // 等待约30ms
    
    // 释放
    key_right = 1'b1;   #1000;
    key_right = 1'b0;   #500;
    key_right = 1'b1;
    
    #20_000_000;
    
    //============================================================
    // 测试用例3：双闪功能
    //============================================================
    $display("=== 测试3: 双闪功能 ===");
    key_haz = 1'b0;     #1000;
    key_haz = 1'b1;     #500;
    key_haz = 1'b0;     #800;
    key_haz = 1'b1;     #300;
    key_haz = 1'b0;
    
    #30_000_000;
    
    // 释放
    key_haz = 1'b1;     #1000;
    key_haz = 1'b0;     #500;
    key_haz = 1'b1;     #300;
    key_haz = 1'b0;
    key_haz = 1'b1;
    
    #20_000_000;
    
    //============================================================
    // 测试用例4：同时按下左+右 → 双闪
    //============================================================
    $display("=== 测试4: 左+右同时按下 ===");
    key_left  = 1'b0;   // 同时按下
    key_right = 1'b0;
    
    #30_000_000;
    
    // 同时释放
    key_left  = 1'b1;
    key_right = 1'b1;
    
    #20_000_000;
    
    //============================================================
    // 测试用例5：模式切换（左转→右转）
    //============================================================
    $display("=== 测试5: 模式切换（左转→右转） ===");
    // 先进入左转
    key_left = 1'b0;    #20_000_000;
    key_left = 1'b1;    #10_000_000;
    
    // 切换到右转
    key_right = 1'b0;   #20_000_000;
    key_right = 1'b1;   #10_000_000;
    
    // 再切换回左转
    key_left = 1'b0;    #20_000_000;
    key_left = 1'b1;    #10_000_000;
    
    //============================================================
    // 结束仿真
    //============================================================
    #100_000;
    $display("=== 仿真结束 ===");
    $stop;
end

//================================================================
// 模块实例化
//================================================================
top u_top (
    .clk        (clk        ),
    .rst_n      (rst_n      ),
    .key_left   (key_left   ),
    .key_right  (key_right  ),
    .key_haz    (key_haz    ),
    .led        (led        )
);

//================================================================
// 流水灯状态监控（在每个LED变化时打印当前值）
//================================================================
reg [3:0] led_prev;
always @(posedge clk) begin
    led_prev <= led;
    if (led != led_prev) begin
        $display("时间=%0tns  LED=4'b%b", $time, led);
    end
end

//================================================================
// 波形导出设置（供 ModelSim/Questasim 使用）
//================================================================
initial begin
    $dumpfile("tb_top.vcd");
    $dumpvars(0, tb_top);
end

endmodule
